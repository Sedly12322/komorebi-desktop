impl Lang {
    pub fn from_code(code: &str) -> Self {
        if code.trim().eq_ignore_ascii_case("cs") {
            Self::Cs
        } else {
            Self::En
        }
    }

    pub fn code(&self) -> &'static str {
        match self {
            Self::En => "en",
            Self::Cs => "cs",
        }
    }
}

