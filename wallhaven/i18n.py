class I18nManager(QObject):
    language_changed = pyqtSignal(str)

    def __init__(self):
        super().__init__()
        # Determine language from config, defaulting to English ("en")
        saved_lang = config.get("language", "en")
        if saved_lang and saved_lang in TRANSLATIONS:
            self._current_lang = saved_lang
        else:
            self._current_lang = "en"
            config.set("language", "en")

    @property
    def current_language(self) -> str:
        return self._current_lang

    def set_language(self, lang: str):
        if lang in TRANSLATIONS and lang != self._current_lang:
            self._current_lang = lang
            config.set("language", lang)
            self.language_changed.emit(lang)

    def tr(self, key: str, **kwargs) -> str:
        text = TRANSLATIONS.get(self._current_lang, {}).get(key)
        if text is None:
            # Fallback to English
            text = TRANSLATIONS["en"].get(key, key)
        if kwargs:
            try:
                return text.format(**kwargs)
            except Exception:
                return text
        return text


i18n = I18nManager()
tr = i18n.tr
